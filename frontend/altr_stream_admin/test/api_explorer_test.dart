      'ApiCurlGenerator generates multi-line curl string with headers and body',
      () {
        final curl = ApiCurlGenerator.generate(
          method: 'POST',
          url: 'http://localhost:8000/api/v1/execute',
          headers: {'X-Custom': 'val'},
          body: '{"query": "SELECT 1"}',
        );

        expect(
          curl.contains('curl -X POST "http://localhost:8000/api/v1/execute"'),
          isTrue,
        );
        expect(curl.contains('-H "Content-Type: application/json"'), isTrue);
        expect(curl.contains('-H "X-Custom: val"'), isTrue);
        expect(curl.contains("-d '{\"query\": \"SELECT 1\"}'"), isTrue);
      },
    );
