    test('OpenApiParser parses endpoints, methods, and tags dynamically', () {
      final parsed = OpenApiParser.parse(sampleOpenApiSpec);

      expect(parsed.title, 'Altr Stream Query Engine');
      expect(parsed.version, '0.8.0');
      expect(parsed.endpoints.length, 9);

      // Discovered methods: GET, POST, DELETE
      expect(parsed.discoveredMethods.contains('GET'), isTrue);
      expect(parsed.discoveredMethods.contains('POST'), isTrue);
      expect(parsed.discoveredMethods.contains('DELETE'), isTrue);

      // Discovered tags
      expect(parsed.discoveredTags.contains('Execution'), isTrue);
      expect(parsed.discoveredTags.contains('Data Sources'), isTrue);
      expect(parsed.discoveredTags.contains('Registry'), isTrue);
      expect(parsed.discoveredTags.contains('System'), isTrue);
    });

    test(
      'OpenApiParser generates intelligent request body samples from schema with refs',
      () {
        final parsed = OpenApiParser.parse(sampleOpenApiSpec);

        final executeEp = parsed.endpoints.firstWhere(
          (e) => e.path == '/api/v1/execute' && e.method == 'POST',
        );
        expect(executeEp.hasRequestBody, isTrue);
        expect(executeEp.requestBody, isNotNull);
        expect(executeEp.requestBody!.sampleJson.contains('"query"'), isTrue);
        expect(executeEp.requestBody!.sampleJson.contains('"limit"'), isTrue);

        final alignEp = parsed.endpoints.firstWhere(
          (e) => e.path.contains('/align/suggestions'),
        );
        expect(alignEp.hasRequestBody, isTrue);
        expect(alignEp.requestBody!.sampleJson.contains('"source_id"'), isTrue);
        expect(alignEp.requestBody!.sampleJson.contains('"proposals"'), isTrue);
      },
    );

    test(
      'ApiEndpoint matchesSearch performs case-insensitive search across attributes',
      () {
        final parsed = OpenApiParser.parse(sampleOpenApiSpec);
        final alignEp = parsed.endpoints.firstWhere(
          (e) => e.path.contains('/align/suggestions'),
        );

        // Path match
        expect(alignEp.matchesSearch('align'), isTrue);
        expect(alignEp.matchesSearch('ALIGN'), isTrue);
        expect(alignEp.matchesSearch('suggestions'), isTrue);

        // Method match
        expect(alignEp.matchesSearch('post'), isTrue);

        // Tag match
        expect(alignEp.matchesSearch('registry'), isTrue);

        // Summary match
        expect(alignEp.matchesSearch('Ingest'), isTrue);

        // Parameter match
        expect(alignEp.matchesSearch('confidence_threshold'), isTrue);
        expect(alignEp.matchesSearch('model_id'), isTrue);

        // Non-matching
        expect(alignEp.matchesSearch('nonexistent_keyword_xyz'), isFalse);
      },
    );

